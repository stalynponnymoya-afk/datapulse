def consultar_grafo_y_generar_plan(mapeo_groq: dict, kg: nx.DiGraph) -> dict:
    plan_de_accion = {}

    for columna, clasificacion in mapeo_groq.items():
        source = clasificacion.get("source")
        target = clasificacion.get("target")

        # Caso 1: Groq determinó que la columna no requiere limpieza o no tiene problemas
        if source == "Ninguno" or target == "Ninguno":
            plan_de_accion[columna] = {
                "ruta": "Pasar_Sin_Cambios",
                "accion": "noop",
                "confianza": 1.0,
                "parametros": {},
                "justificacion": "La columna no presenta anomalías estructurales o estadísticas iniciales."
            }
            continue

        # Caso 2: La regla conceptual existe de forma exacta en tu Grafo NetworkX
        if kg.has_edge(source, target):
            # Extraemos los metadatos almacenados en el borde
            datos_borde = kg.get_edge_data(source, target)

            plan_de_accion[columna] = {
                "ruta": "Grafo_Determinista",
                "accion": datos_borde.get("accion"),
                "confianza": datos_borde.get("confidence", datos_borde.get("confianza", 0.99)),
                "parametros": datos_borde.get("parametros", {}),
                "justificacion": datos_borde.get("justificacion_es", "Regla de calidad estandarizada aplicada.")
            }

        # Caso 3: RUTA DE FALLBACK (La columna es de otro dominio o no está en el grafo)
        else:
            plan_de_accion[columna] = {
                "ruta": "Fallback_Inteligente_LLM",
                "accion": "evaluar_limpieza_dinamica_groq",
                "confianza": 0.70,  # Máximo por diseño para decisiones heurísticas fuera del grafo
                "parametros": {"concepto_inferido": source, "problema_inferido": target},
                "justificacion": f"No se encontró una regla rígida para {source} -> {target}. Se delega la estrategia adaptativa al LLM."
            }

    return plan_de_accion

