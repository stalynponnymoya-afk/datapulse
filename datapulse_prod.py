def main() -> None:
    """
    Punto de entrada principal para ejecución local.
    En Colab: usar run_datapulse(filepath) directamente.
    """
    global kg
    if kg is None:
        kg = KNOWLEDGE_GRAPH

    print(f"📊 Grafo cargado: {kg.number_of_nodes()} nodos, {kg.number_of_edges()} edges")

    # ── Detectar archivo de datos ─────────────────────────────────
    formatos = ["*.csv", "*.xlsx", "*.json", "*.parquet"]
    archivos_locales = []
    for carpeta in (".", "data", "datasets"):
        for pat in formatos:
            archivos_locales.extend(sorted(glob.glob(os.path.join(carpeta, pat))))
    # Los reportes de salida no son datasets de entrada
    archivos_locales = [
        p for p in archivos_locales
        if os.path.basename(p) not in ("quality_report.json", "cleaning_log.json")
    ]

    if archivos_locales:
        filepath = os.path.abspath(archivos_locales[0])
        print(f"📂 Archivo detectado: {filepath}")
    else:
        filepath = os.path.abspath("ventas_prueba.csv")
        _generate_mock_dataset(filepath)

    print(f"\n🚀 Iniciando DataPulse sobre: {os.path.basename(filepath)}\n")

    final_state = run_datapulse(filepath)
    _print_results(final_state)

    # ── Descarga en Colab ─────────────────────────────────────────
    _descargar_en_colab(final_state)


def _descargar_en_colab(final_state: dict) -> None:
    """Descarga processed_data.csv desde la ruta real del intento (solo en Colab)."""
    try:
        from google.colab import files
    except ImportError:
        return
    ruta = final_state.get("ruta_processed")
    if not ruta:
        print("ℹ️ No hay processed_data.csv que descargar.")
        return
    try:
        files.download(ruta)
    except FileNotFoundError:
        print(f"⚠️ No se encontró {ruta}; no se pudo descargar.")


if __name__ == "__main__":
    main()
