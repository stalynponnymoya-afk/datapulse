def _build_files_to_commit(state: DataPulseState, ts: str) -> list:
    """Construye la lista (path_en_repo, contenido) de archivos a publicar."""
    files_to_commit = []

    # 1. Auditoría
    audit = {
        "timestamp": ts,
        "filename_original": state["filename"],
        "score_antes": state.get("score_antes"),
        "score_despues": state.get("score_despues"),
        "score_reportado": state.get("score_reportado"),
        "decisiones_knowledge_graph": sum(
            1 for a in state.get("plan_acciones", [])
            if a.get("fuente_decision") == "knowledge_graph"
        ),
        "decisiones_llm_fallback": sum(
            1 for a in state.get("plan_acciones", [])
            if a.get("fuente_decision") == "llm_fallback"
        ),
        "problemas_sin_regla": state.get("sin_regla", []),
        "modo_salida": state.get("modo_salida"),
        "omitidos_por_modo": state.get("omitidos_por_modo", []),
        "decisiones_negativos": state.get("decisiones_negativos", {}),
        "discrepancias_negativos": state.get("discrepancias_negativos", []),
        "columnas_nuevas_no_evaluadas": state.get("columnas_nuevas", []),
        "columnas_originales_eliminadas": state.get("columnas_eliminadas", []),
        "avisos_diagnostico": state.get("avisos_diagnostico", []),
        "respuesta_cruda_diagnostico": state.get("respuesta_cruda_diagnostico"),
        "plan_acciones": state.get("plan_acciones", [])
    }
    files_to_commit.append((f"outputs/{ts}/audit_log.json", json.dumps(audit, ensure_ascii=False, indent=2)))

    # 2. Agregar los archivos generados reales de OpenHands si existen en el estado
    archivos_generados = state.get("archivos_generados", {})

    # Si OpenHands no los tiene, pero tenemos código en 'codigo', lo guardamos como fallback
    if not archivos_generados and state.get("codigo"):
        archivos_generados = {"datapulse_pipeline.py": state["codigo"]}

    # Un archivo se publica una sola vez por destino. Si hay dos versiones con el
    # mismo nombre (p. ej. la reconstruida desde los eventos de OpenHands y la
    # leída de la rama), gana la que está guardada por su nombre simple: la de
    # la rama, que es la que se ejecutó.
    por_destino: Dict[str, tuple] = {}
    for original_path, content in archivos_generados.items():
        fname = os.path.basename(original_path)
        if fname in por_destino and original_path != fname:
            continue
        por_destino[fname] = (original_path, content)

    for original_path, content in por_destino.values():
        fname = os.path.basename(original_path)

        # Omitir archivos vacíos o directorios
        if not fname or not content:
            continue

        # Regla de tamaño: si supera 50MB, omitimos
        try:
            content_bytes = content.encode('utf-8')
        except AttributeError:
            content_bytes = content

        if len(content_bytes) > 50 * 1024 * 1024:
            print(f"   ⚠️ Archivo {fname} omitido de GitHub por superar el límite de 50MB ({len(content_bytes)/(1024*1024):.2f}MB).")
            continue

        # Ubicar en la raíz o bajo outputs/{ts}/ según su tipo
        if fname in ("datapulse_pipeline.py", "quality_report.json", "cleaning_log.json", "eda_report.html") or "_clean.csv" in fname or "processed_data.csv" in fname:
            files_to_commit.append((fname, content))
        else:
            files_to_commit.append((f"outputs/{ts}/{fname}", content))

    return files_to_commit


def _save_outputs_locally(files_to_commit: list, ts: str) -> str:
    """Guarda todos los archivos generados en outputs/{ts}/ y retorna la ruta."""
    out_dir = os.path.join("outputs", ts)
    os.makedirs(out_dir, exist_ok=True)
    for path_in_repo, content in files_to_commit:
        dest = os.path.join(out_dir, os.path.basename(path_in_repo))
        if isinstance(content, (bytes, bytearray)):
            with open(dest, "wb") as f:
                f.write(content)
        else:
            with open(dest, "w", encoding="utf-8") as f:
                f.write(content)
        print(f"   💾 Guardado local: {dest}")
    return out_dir


def node_commit(state: DataPulseState) -> DataPulseState:
    ts = datetime.now().strftime("%Y%m%d-%H%M%S")
    files_to_commit = _build_files_to_commit(state, ts)

    # Sin token → publicar en el sistema de archivos local
    if not GITHUB_TOKEN:
        print("   ℹ️ GITHUB_TOKEN vacío — guardando salidas localmente en outputs/.")
        _save_outputs_locally(files_to_commit, ts)
        return {"github_url": f"local://outputs/{ts}"}

    falta = _falta_repo_github()
    if falta:
        print(f"   ⚠️ {falta}")
        print("   ℹ️ Guardando salidas localmente en outputs/.")
        _save_outputs_locally(files_to_commit, ts)
        return {"github_url": f"local://outputs/{ts}"}

    try:
        repo = _get_github_repo()

        # Política de datos: sin permiso solo se suben el script, los reportes
        # y audit_log.json. Todo se conserva igualmente en local.
        subir_datos, motivo = _subida_datos_permitida(repo)
        if not subir_datos:
            omitidos = [p for p, _ in files_to_commit if _es_archivo_datos(p)]
            if omitidos:
                print(f"   🔐 Subida de datos no permitida ({motivo}); se guardan solo en local:")
                for p in omitidos:
                    print(f"      - {p}")
                _save_outputs_locally(
                    [(p, c) for p, c in files_to_commit if _es_archivo_datos(p)], ts
                )
            files_to_commit = [(p, c) for p, c in files_to_commit if not _es_archivo_datos(p)]

        try:
            base = repo.get_branch("main")
        except Exception:
            base = repo.get_branch("master")

        branch_name = f"feature/datapulse-{ts}"

        # Crear rama
        repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=base.commit.sha)

        # Commit y push de cada archivo — eliminar versión previa si existe
        commit_msg = f"DataPulse run {ts} — score: {state['score_despues']}"
        for path_in_repo, content in files_to_commit:
            try:
                existing = repo.get_contents(path_in_repo, ref=branch_name)
                repo.delete_file(
                    path=path_in_repo,
                    message=f"chore: remove old {os.path.basename(path_in_repo)}",
                    sha=existing.sha,
                    branch=branch_name,
                )
            except Exception:
                pass  # archivo nuevo, nada que eliminar
            # PyGithub codifica en Base64 internamente: pasar el contenido tal cual
            repo.create_file(
                path=path_in_repo,
                message=commit_msg,
                content=content,
                branch=branch_name,
            )
            print(f"   ✅ Versionado en GitHub: {path_in_repo}")

        url = f"https://github.com/{GITHUB_USERNAME}/{GITHUB_REPO}/tree/{branch_name}"
        return {"github_url": url}

    except Exception as e:
        # 403 Forbidden, token inválido o falta de permisos (p. ej. un usuario
        # externo que clona el repo): conservar el trabajo en disco.
        print(f"   ⚠️ GitHub no disponible ({type(e).__name__}: {str(e)[:200]})")
        print("   ℹ️ Guardando salidas localmente en outputs/.")
        _save_outputs_locally(files_to_commit, ts)
        return {"github_url": f"local://outputs/{ts}"}


