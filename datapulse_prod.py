def extract_json_from_markdown(text: str) -> dict:
    """Extrae JSON de respuestas del LLM que vienen envueltas en markdown."""
    text = text.strip()
    if text.startswith("```json"):
        text = text[7:]
    if text.startswith("```"):
        text = text[3:]
    if text.endswith("```"):
        text = text[:-3]
