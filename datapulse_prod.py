def _download_github_file(repo_path: str, branch: str, local_dest: str) -> None:
    """Descarga un archivo del repo de GitHub a una ruta local temporal."""
    falta = _falta_repo_github()
    if falta:
        raise ValueError(f"No se puede leer '{repo_path}' de GitHub. {falta}")
    repo = _get_github_repo()
    contents = repo.get_contents(repo_path, ref=branch)
    with open(local_dest, "wb") as f:
        f.write(contents.decoded_content)
    print(f"   📥 Descargado desde GitHub: {repo_path} ({len(contents.decoded_content):,} bytes)")


def run_datapulse(
    filepath: str = "",
    github_file: str = "",
    github_branch: str = "",
) -> dict:
    """
    Ejecuta el pipeline completo sobre un archivo de datos.

    Uso — archivo local:
        run_datapulse("/content/mis_datos.csv")

    Uso — archivo ya en GitHub (recomendado para evitar re-uploads):
        run_datapulse(github_file="data/dummy_data_hss.csv")
        run_datapulse(github_file="data/ventas.xlsx", github_branch="dev")

    Si GITHUB_DATA_FILE está configurado arriba, no hace falta pasar argumentos:
        run_datapulse()
    """
    global kg
    if kg is None:
        kg = KNOWLEDGE_GRAPH
    aplicar_dominios_activos()
    validar_grafo(kg)                     # también las ediciones en caliente (dp.kg.add_edge...)
    modo_salida = modo_salida_vigente()   # falla aquí, antes de llamar al LLM, si no es válido

    # Resolver fuente del archivo
    gh_file   = github_file   or GITHUB_DATA_FILE
    gh_branch = github_branch or GITHUB_DATA_BRANCH or "main"

    if gh_file:
        # Archivo ya existe en GitHub — descargar a /tmp para que node_ingestar lo lea
        filename   = os.path.basename(gh_file)
        file_ext   = filename.rsplit(".", 1)[-1].lower()
        local_path = f"/tmp/datapulse_{filename}"
        _download_github_file(gh_file, gh_branch, local_path)
        source_branch = gh_branch
        source_path   = gh_file
    elif filepath:
        filename      = os.path.basename(filepath)
        file_ext      = filename.rsplit(".", 1)[-1].lower()
        local_path    = os.path.abspath(filepath)
        source_branch = None   # archivo local → node_ejecutar lo subirá
        source_path   = None
    else:
        raise ValueError(
            "Debes indicar un archivo. Ejemplos:\n"
            "  run_datapulse('/content/datos.csv')\n"
            "  run_datapulse(github_file='data/dummy_data_hss.csv')\n"
            "  O configurar GITHUB_DATA_FILE al inicio del script."
        )

    initial_state: DataPulseState = {
        "filename":             filename,
        "filename_path":        local_path,
        "file_ext":             file_ext,
        "metadata":             {},
        "diagnostico":          {},
        "decisiones_negativos": {},
        "discrepancias_negativos": [],
        "avisos_diagnostico":   [],
        "respuesta_cruda_diagnostico": None,
        "acciones_grafo":       {},
        "modo_salida":          modo_salida,
        "omitidos_por_modo":    [],
        "plan_acciones":        [],
        "sin_regla":            [],
        "brief_tecnico":        "",
        "codigo":               "",
        "intentos":             0,
        "error_history":        [],
        "github_source_branch": source_branch,
        "github_source_path":   source_path,
        "score_antes":        None,
        "score_despues":      0,
        "score_reportado":    None,
        "ruta_processed":     None,
        "processed_esperado": False,
        "residuales":         None,
        "columnas_nuevas":    [],
        "columnas_eliminadas": [],
        "mensaje_ejecucion":  None,
        "directorio_salida":  None,
        "archivos_generados": {},
        "openhands_status":   "",
        "github_url":         None,
    }

    app = build_datapulse_graph()
    final_state = app.invoke(initial_state)

    # Informe final determinista, fuera del grafo (no es un nodo)
    try:
        final_state["informe_final"] = generar_informe_final(final_state)
    except Exception as exc:
        print(f"   ⚠️ No se pudo generar el informe final: {type(exc).__name__}: {exc}")
        final_state["informe_final"] = None
    return final_state


def _print_results(final_state: dict) -> None:
    print("\n" + "=" * 60)
    print("📊 RESULTADO FINAL DATAPULSE")
    print("=" * 60)
    print(f"Status OpenHands : {final_state['openhands_status']}")
    print(f"Score antes      : {final_state.get('score_antes')}/100")
    print(f"Score calidad    : {final_state['score_despues']}/100 (validación independiente)")
    print(f"Score reportado  : {final_state.get('score_reportado')} (informativo)")
    print(f"Intentos usados  : {final_state['intentos']}")
    print(f"GitHub URL       : {final_state.get('github_url', 'N/A')}")
    informe = final_state.get("informe_final") or {}
    if informe:
        print(f"Informe final    : {informe.get('ruta')}")
        print(f"Sin limpiar      : {len(informe.get('valores_sin_limpiar') or [])} problemas | "
              f"sin regla en el grafo: {len(informe.get('problemas_sin_regla') or [])}")

    archivos = final_state.get("archivos_generados", {})
    if archivos:
        print(f"\n📁 Archivos generados ({len(archivos)}):")
        for p, c in archivos.items():
            fname = os.path.basename(p)
            print(f"   - {fname} ({len(c)} chars)")

    if final_state.get("error_history"):
        print("\n⚠️  Errores registrados:")
        for idx, err in enumerate(final_state["error_history"], 1):
            print(f"   {idx}. {err[:200]}")


