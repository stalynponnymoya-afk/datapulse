def _leer_contenido_github(repo, path: str, ref: str) -> bytes:
    """Lee un archivo de una rama; usa la API de blobs si supera 1 MB."""
    contents = repo.get_contents(path, ref=ref)
    if isinstance(contents, list):
        raise IsADirectoryError(path)
    data = b""
    try:
        data = contents.decoded_content or b""
    except Exception:
        data = b""
    if not data and getattr(contents, "size", 0):
        blob = repo.get_git_blob(contents.sha)
        data = base64.b64decode(blob.content)
    return data


def _es_no_encontrado(exc: Exception) -> bool:
    """True si la excepción de PyGithub es un 404 (el archivo no existe en la rama)."""
    return getattr(exc, "status", None) == 404 or "404" in str(exc)


def _leer_salidas_rama(repo, rama: str, run_dir: str, nombres) -> tuple:
    """
    Descarga de la rama de trabajo las salidas indicadas y las guarda en
    ``run_dir``. Devuelve ({nombre: bytes} leídos, {nombre: error} de los que
    existían o podían existir pero NO se pudieron leer — distinto de un 404).
    """
    leidos: Dict[str, bytes] = {}
    errores: Dict[str, str] = {}
    for nombre in nombres:
        try:
            data = _leer_contenido_github(repo, nombre, rama)
        except Exception as exc:
            if _es_no_encontrado(exc):
                print(f"   ⚠️ {nombre} no está en la rama {rama}")
            else:
                errores[nombre] = f"{type(exc).__name__}: {str(exc)[:200]}"
                print(f"   ⚠️ {nombre} no se pudo leer de {rama} ({errores[nombre]})")
            continue
        os.makedirs(run_dir, exist_ok=True)
        with open(os.path.join(run_dir, nombre), "wb") as f:
            f.write(data)
        leidos[nombre] = data
        print(f"   📥 {nombre} leído de {rama} ({len(data):,} bytes)")
    return leidos, errores


def _procesar_eventos_openhands(eventos: List[Dict[str, Any]], archivos: Dict[str, str],
                                terminal_outputs: List[str]) -> Optional[str]:
    """
    Procesa una lista de eventos de OpenHands (cualquier página).

    - FileEditorAction "create" / "str_replace": reconstruye en ``archivos`` los
      archivos que editó el agente.
    - Observaciones con texto: se añaden a ``terminal_outputs``.
    Devuelve el mensaje del último FinishAction de la lista, o None.
    """
    finish_msg = None
    for ev in eventos:
        if not isinstance(ev, dict):
            continue
        act = ev.get("action")
        if isinstance(act, dict):
            kind = act.get("kind", "")
            if kind == "FileEditorAction":
                path = act.get("path", "")
                cmd = act.get("command", "")
                if cmd == "create" and act.get("file_text"):
                    archivos[path] = act["file_text"]
                elif cmd == "str_replace" and path in archivos:
                    old = act.get("old_str", "")
                    new = act.get("new_str", "")
                    if old:
                        archivos[path] = archivos[path].replace(old, new)
            elif kind == "FinishAction":
                finish_msg = act.get("message", "")
        obs = ev.get("observation")
        if isinstance(obs, dict):
            oc = obs.get("content", [])
            if isinstance(oc, list):
                for c in oc:
                    if isinstance(c, dict) and c.get("text"):
                        terminal_outputs.append(c["text"])
    return finish_msg


def _clave_evento(ev: Dict[str, Any]) -> str:
    """Identificador estable de un evento: su id si lo trae; si no, su contenido."""
    if ev.get("id") is not None:
        return f"id:{ev['id']}"
    return "json:" + json.dumps(ev, sort_keys=True, default=str, ensure_ascii=False)


def _leer_eventos_openhands(base: str, conv_id: str, headers: Dict[str, str],
                            max_paginas: Optional[int] = None) -> tuple:
    """
    Lee todos los eventos de una conversación de OpenHands, página a página.

    La API pagina así: la página siguiente se pide con ``page_id`` igual al
    ``next_page_id`` de la respuesta anterior (GET .../events/search). Antes se
    usaba ``start_id``, que la API no reconoce: devolvía siempre la misma página
    y la lectura podía tardar decenas de minutos.

    Protecciones contra bucles (cada una corta la lectura con un aviso):
    - ``next_page_id`` repetido;
    - una página que no trae eventos nuevos (se deduplican por id);
    - más de ``max_paginas`` páginas (por defecto OH_MAX_PAGINAS_EVENTOS).

    Devuelve (eventos_sin_duplicados, avisos). Si la primera página falla,
    devuelve ([], [aviso]) y node_ejecutar sigue con la lectura de la rama.
    """
    limite = max_paginas or OH_MAX_PAGINAS_EVENTOS
    url_base = f"{base}/conversation/{conv_id}/events/search?limit={OH_EVENTOS_POR_PAGINA}"
    eventos: List[Dict[str, Any]] = []
    avisos: List[str] = []
    vistos: set = set()
    tokens_usados: set = set()
    page_id: Optional[str] = None

    for numero in range(1, limite + 1):
        url = url_base + (f"&page_id={quote(str(page_id), safe='')}" if page_id else "")
        r = requests.get(url, headers=headers, timeout=30)
        if r.status_code != 200:
            avisos.append(f"Eventos de OpenHands: la página {numero} respondió HTTP {r.status_code}; "
                          "se usan los eventos leídos hasta ahí.")
            break
        datos = r.json() or {}
        items = [ev for ev in (datos.get("items") or []) if isinstance(ev, dict)]
        nuevos = []
        for ev in items:
            clave = _clave_evento(ev)
            if clave not in vistos:
                vistos.add(clave)
                nuevos.append(ev)
        eventos.extend(nuevos)
        if numero == 1:
            print(f"   📋 Eventos: {len(nuevos)}")
        else:
            print(f"   📋 Página {numero}: {len(nuevos)} eventos nuevos")

        siguiente = datos.get("next_page_id")
        if not siguiente:
            break
        if numero > 1 and not nuevos:
            avisos.append(f"Eventos de OpenHands: la página {numero} no trajo eventos nuevos; "
                          "se detiene la paginación.")
            break
        if siguiente == page_id or siguiente in tokens_usados:
            avisos.append("Eventos de OpenHands: next_page_id repetido; se detiene la paginación.")
            break
        tokens_usados.add(siguiente)
        page_id = siguiente
    else:
        avisos.append(f"Eventos de OpenHands: se alcanzó el máximo de {limite} páginas; "
                      "puede haber eventos sin leer (los archivos de salida se leen de la rama).")

    for aviso in avisos:
        print(f"   ⚠️ {aviso}")
    return eventos, avisos


def node_ejecutar(state: DataPulseState) -> DataPulseState:
    """
    OpenHands Cloud API — sube archivo a GitHub + flujo real de 5 pasos.
    Sin OPENHANDS_API_KEY, genera y ejecuta el pipeline localmente con el LLM configurado.
    """
    if not OPENHANDS_API_KEY:
        print(f"   ℹ️ OPENHANDS_API_KEY vacío — generando pipeline local con {describir_llm()}...")
        return _run_local_groq_pipeline(state)

    falta = _falta_repo_github()
    if not GITHUB_TOKEN:
        # Sin token PyGithub lanza un AssertionError vacío; mejor un mensaje claro.
        falta = (f"{falta} " if falta else "") + (
            "Falta GITHUB_TOKEN: OpenHands trabaja sobre una rama del repositorio."
        )
    if falta:
        msg = f"Modo OpenHands no disponible. {falta} Usa el modo local (deja OPENHANDS_API_KEY vacío)."
        print(f"   ❌ {msg}")
        return _rechazo_openhands(state, msg)

    headers = {
        "Authorization": f"Bearer {OPENHANDS_API_KEY}",
        "Content-Type": "application/json"
    }
    base = "https://app.all-hands.dev/api/v1"

    try:
        repo = _get_github_repo()

        # ── Política de subida de datos ─────────────────────────
        subir_datos, motivo = _subida_datos_permitida(repo)
        archivo_en_github = bool(
            state.get("github_source_branch") and state.get("github_source_path")
        )
        if not subir_datos:
            # Sin permiso no se puede subir el dataset NI leer de vuelta
            # processed_data.csv: el resultado nunca se podría validar, así
            # que no se crea rama ni sandbox.
            que_falla = (
                "los resultados (processed_data.csv) no se podrían leer de vuelta para "
                "validarlos"
                if archivo_en_github
                else "habría que subir el dataset a GitHub y los resultados no se podrían leer de vuelta"
            )
            msg = (
                f"Modo OpenHands no arranca: {que_falla}, porque la subida de datos no está "
                f"permitida ({motivo}). Usa el modo local (deja OPENHANDS_API_KEY vacío) o, "
                "si el repo es privado y aceptas subir los datos, define "
                "DATAPULSE_PERMITIR_SUBIDA_DATOS=1."
            )
            print(f"   ❌ {msg}")
            return _rechazo_openhands(state, msg)
        print(f"   🔐 Subida de datos: sí ({motivo})")

        # ── PASO 0: Preparar rama de trabajo con el archivo de datos ──
        # Siempre se crea una rama nueva: el agente hace commit de sus salidas
        # ahí y nunca directamente en main ni en la rama de origen.
        fecha = datetime.now().strftime("%Y%m%d-%H%M%S")
        rama  = f"data/datapulse-{fecha}"
        if state.get("github_source_branch") and state.get("github_source_path"):
            # El archivo YA está en GitHub — se ramifica desde su rama, sin subir nada
            base_sha  = repo.get_branch(state["github_source_branch"]).commit.sha
            data_path = state["github_source_path"]
            repo.create_git_ref(ref=f"refs/heads/{rama}", sha=base_sha)
            print(f"   ✅ Usando archivo del repo: {data_path} (rama de trabajo: {rama})")
        else:
            # Archivo local — crear rama temporal y subir
            print(f"   📤 Subiendo {state['filename']} a GitHub...")
            try:
                base_sha = repo.get_branch("main").commit.sha
            except Exception:
                base_sha = repo.get_branch("master").commit.sha
            repo.create_git_ref(ref=f"refs/heads/{rama}", sha=base_sha)
            with open(state["filename_path"], "rb") as f:
                file_content = f.read()
            data_path = f"data/{state['filename']}"
            try:
                existing = repo.get_contents(data_path, ref=rama)
                repo.delete_file(
                    path=data_path,
                    message=f"data: remove old {state['filename']}",
                    sha=existing.sha,
                    branch=rama,
                )
            except Exception:
                pass
            repo.create_file(
                path=data_path,
                message=f"data: upload {state['filename']} para DataPulse",
                content=file_content,
                branch=rama,
            )
            print(f"   ✅ Archivo subido a {rama}:{data_path}")

        # ── PASO 1: Crear task con rama del archivo ─────────────
        resp = requests.post(
            f"{base}/app-conversations",
            headers=headers,
            json={
                "selected_repository": f"{GITHUB_USERNAME}/{GITHUB_REPO}",
                "selected_branch": rama,
            },
            timeout=30,
        )
        resp.raise_for_status()
        task_id = resp.json()["id"]
        print(f"   📤 Task: {task_id[:16]}...")

        # ── PASO 2: Esperar READY ──────────────────────────────
        conv_id = None
        START_POLL_INTERVAL = 10
        start_polls = max(int(OH_STARTUP_TIMEOUT_SEG / START_POLL_INTERVAL), 20)
        for i in range(start_polls):
            time.sleep(START_POLL_INTERVAL)
            r = requests.get(
                f"{base}/app-conversations/start-tasks?ids={task_id}",
                headers=headers, timeout=30,
            )
            if r.status_code != 200:
                continue
            data = r.json()
            if not (isinstance(data, list) and data and data[0]):
                continue
            st = data[0].get("status", "")
            print(f"   ⏳ Start poll {i+1}/{start_polls}: {st}")
            if st == "READY":
                conv_id = data[0].get("app_conversation_id")
                break
            if st in ("ERROR", "FAILED"):
                raise Exception(f"start-task: {st}")

        if not conv_id:
            raise Exception("Timeout esperando READY")
        print(f"   ✅ READY: {conv_id[:16]}...")

        # ── PASO 3: Enviar brief con referencia al archivo ──────
        mensaje = _construir_brief_openhands(state, data_path, rama)

        r = requests.post(
            f"{base}/app-conversations/{conv_id}/send-message",
            headers=headers,
            json={"content": [{"type": "text", "text": mensaje}]},
            timeout=15,
        )
        r.raise_for_status()
        print(f"   📨 Brief enviado ({len(mensaje)} chars)")

        # ── PASO 4: Esperar execution_status terminal ───────────
        POLL_INTERVAL = 15
        MAX_POLLS = max(int(OH_TIMEOUT_SEG / POLL_INTERVAL), 4)
        final_status = "timeout"

        for i in range(MAX_POLLS):
            time.sleep(POLL_INTERVAL)
            r = requests.get(
                f"{base}/app-conversations?ids={conv_id}",
                headers=headers, timeout=30,
            )
            if r.status_code != 200:
                continue
            data = r.json()
            item = data[0] if isinstance(data, list) and data and data[0] else None
            if not item:
                continue
            es = (item.get("execution_status") or "").lower()
            print(f"   ⏳ Exec poll {i+1}/{MAX_POLLS}: {es}")
            if es in ("finished", "error", "stuck", "stopped"):
                final_status = es
                break

        print(f"   📊 Status: {final_status}")

        # ── PASO 5: Extraer código y score de eventos ───────────
        archivos = {}
        terminal_outputs = []
        eventos, _avisos_eventos = _leer_eventos_openhands(base, conv_id, headers)
        finish_msg = _procesar_eventos_openhands(eventos, archivos, terminal_outputs) or ""

        # Elegir script principal (.py más grande)
        codigo = ""
        py_files = {p: c for p, c in archivos.items() if p.endswith(".py")}
        if py_files:
            main_path = max(py_files, key=lambda p: len(py_files[p]))
            codigo = py_files[main_path]
            print(f"   📝 Script: {main_path.split('/')[-1]} ({len(codigo)} chars)")

        print(f"   📁 Archivos: {len(archivos)}")
        for p in archivos:
            print(f"      - {p.split('/')[-1]} ({len(archivos[p])} chars)")

        # Score declarado por el agente: solo informativo (sin fallback fijo).
        # El score real lo calcula node_validar_score sobre processed_data.csv.
        score_reportado = None
        for path, content in archivos.items():
            if "quality" in path.lower() and path.endswith(".json"):
                score_reportado = _leer_score_reportado(content)
                if score_reportado is not None:
                    break

        if score_reportado is None:
            for out in terminal_outputs:
                m = re.search(r'"score"\s*[:\s]+(\d+)', out)
                if m:
                    score_reportado = int(m.group(1))
                    break

        if finish_msg:
            print(f"   💬 {finish_msg[:150]}")
        print(f"   📝 Score reportado por OpenHands (informativo): {score_reportado}")

        # ── PASO 6: Leer de la rama de trabajo lo que escribió el script ──
        # Los eventos solo traen lo editado con FileEditorAction; lo que el
        # script escribe al ejecutarse (processed_data.csv, reportes) se lee
        # del commit que el agente hizo en la rama.
        run_dir = os.path.join("outputs", fecha + "-openhands")
        leidos, errores_lectura = _leer_salidas_rama(repo, rama, run_dir, SALIDAS_OPENHANDS)
        for nombre, contenido in leidos.items():
            # La versión de la rama es la que realmente se ejecutó: reemplaza a
            # la reconstruida desde los eventos (misma base de nombre), para no
            # publicar el mismo archivo dos veces.
            for ruta_evento in [p for p in archivos if p != nombre and os.path.basename(p) == nombre]:
                del archivos[ruta_evento]
            archivos[nombre] = contenido.decode("utf-8", errors="replace")
        if "datapulse_pipeline.py" in leidos:
            codigo = archivos["datapulse_pipeline.py"]
        if score_reportado is None and "quality_report.json" in archivos:
            score_reportado = _leer_score_reportado(archivos["quality_report.json"])

        ruta_processed = os.path.join(run_dir, "processed_data.csv")
        return {
            "intentos": state.get("intentos", 0) + 1,
            "openhands_status": final_status,
            "mensaje_ejecucion": finish_msg[:1000] or None,
            "score_reportado": score_reportado,
            "ruta_processed": os.path.abspath(ruta_processed) if "processed_data.csv" in leidos else None,
            # Debía existir salvo que la rama no se pudiera leer (no es un 404):
            # en ese caso reintentar el sandbox no lo arreglaría.
            "processed_esperado": "processed_data.csv" not in errores_lectura,
            "directorio_salida": os.path.abspath(run_dir) if leidos else None,
            "codigo": codigo if codigo else "# OpenHands no generó .py",
            "archivos_generados": archivos,
        }

    except Exception as e:
        err_msg = (f"{_etiqueta_intento(state.get('intentos', 0) + 1)}"
                   f"{type(e).__name__}: {str(e)[:300]}")
        print(f"   ❌ {err_msg}")
        return {
            "intentos": state.get("intentos", 0) + 1,
            "openhands_status": "error",
            "error_history": [err_msg],
            "score_reportado": None,
            "ruta_processed": None,
            "processed_esperado": False,
            "archivos_generados": {},
        }


